"""Reproducible developer-designed comparisons; no claim of external blindness.

Targets are generated by separate simulators. No simulator is passed to the
learner or planner. Ablations share grounded evidence, not compute-matched.
"""
import argparse
import json
import random
from .unified import UnifiedMind, jsonable
from .relational import WorldMemory


def symbolic_truth(s,a,kind):
    s=set(s);name,x=a
    if ('ready',x) not in s:return frozenset(s)
    s.remove(('ready',x));s.add(('done',x))
    if kind=='nonlocal':s.add(('lit','hub'))
    return frozenset(s)


def symbolic_fixture(seed,kind):
    rng=random.Random(seed);prefix=f'p{seed}_'
    def item(i,ready,distractor=False):
        x=prefix+str(i);a=('step',x);s=set()
        if ready:s.add(('ready',x))
        if distractor:s.add(('external',f'outside{i}'))
        return frozenset(s),a,symbolic_truth(s,a,kind)
    training=[item(i,r) for i in range(6) for r in (False,True)]
    audits=[item(i,bool(i%2)) for i in range(6,12)]
    held=[item(i,bool(rng.randrange(2)),kind=='local' and i%2==0) for i in range(12,36)]
    return training,audits,held


def symbolic_campaign(seeds):
    result={kind:{mode:dict(correct=0,incorrect=0,abstained=0,audit_passes=0,audits=0) for mode in ('local','counter','combined')} for kind in ('local','nonlocal')}
    for seed in seeds:
        for kind in result:
            fit,audits,test=symbolic_fixture(seed,kind)
            for mode,row in result[kind].items():
                w=WorldMemory(mode)
                for e in fit:w.observe(*e)
                for e in audits:row['audit_passes']+=w.audit(*e);row['audits']+=1
                for s,a,t in test:
                    p=w.predict(s,a);row['abstained' if p is None else 'correct' if p==t else 'incorrect']+=1
    return result


def stage_truth(s,a):
    s=set(s);name,x=a
    before,after={'prep':('raw','ready'),'finish':('ready','done')}[name]
    if (before,x) in s:s.remove((before,x));s.add((after,x))
    return frozenset(s)


def numeric_truth(v,name):
    a,b=v
    return ((a+1)%5,b) if name=='prep' else (a,(b+1)%5)


def build_joint(seed):
    m=UnifiedMind();rng=random.Random(seed);traces=[]
    # Grounded successes and failures with all three local stage contexts.
    for i in range(6):
        x=f'train{seed}_{i}';trace=[]
        for name in ('prep','finish'):
            a=(name,x)
            for tag in ('raw','ready','done'):
                s=frozenset({(tag,x)});t=stage_truth(s,a);m.apply('observe',s,a,t)
            s=frozenset({('raw' if name=='prep' else 'ready',x)});trace.append((s,a,stage_truth(s,a)))
        traces.append(trace)
    for trace in traces[:2]:m.apply('remember',trace)
    for name in ('prep','finish'):
        for i in range(6,12):
            x=f'audit{seed}_{i}';a=(name,x);s=frozenset({(('raw','ready','done')[i%3],x)})
            m.apply('audit',s,a,stage_truth(s,a))
        d=m.discovery;d.apply('new',name,2,5,False,'strict');e=d.episodes[name];xs=list(e.space.states);rng.shuffle(xs)
        for x in xs[:19]:d.apply('observe',name,x,numeric_truth(x,name))
        for x in xs[19:22]:d.apply('audit',name,x,numeric_truth(x,name))
        m.apply('bind',(name,'placeholder'),name)
        for i,v in enumerate(xs[22:25]):
            x=f'jointaudit{seed}_{i}';a=(name,x);s=frozenset({(('raw','ready','done')[i%3],x)})
            if e.passes>=3 and not e.blocked:m.apply('joint_audit',s,v,a,stage_truth(s,a),numeric_truth(v,name))
    return m


def joint_campaign(seeds):
    result={k:dict(success=0,wrong=0,abstained=0,expansions=0) for k in ('joint','joint_no_macros','relational_only','numeric_only')}
    goals=dict(generated=0,replayed_success=0,wrong=0,abstained=0);trials=0
    for seed in seeds:
        m=build_joint(seed);rng=random.Random(seed+2000)
        for i in range(8):
            x=f'held{seed}_{i}';actions=[('prep',x),('finish',x)];s=frozenset({('raw',x)});v=(rng.randrange(5),rng.randrange(5));offset=((i%4),((i//2)%4));goal=((v[0]+offset[0])%5,(v[1]+offset[1])%5);trials+=1
            for mode,row in result.items():
                if mode.startswith('joint'):
                    p=m.plan((s,v),actions,present=[('done',x)],vector=goal,macros=mode=='joint');path=p['path'];row['expansions']+=p['expanded']
                elif mode=='relational_only':
                    p=m.plan((s,None),actions,present=[('done',x)]);path=p['path'];row['expansions']+=p['expanded']
                else:
                    p=m.discovery.plan(m.discovery.episodes['prep'].space,v,goal,['prep','finish']);path=None if p is None else tuple((name,x) for name,_ in p)
                if path is None:row['abstained']+=1;continue
                # Replay primitive transitions in separate simulator.
                fs,ns=s,v
                for a in path:fs=stage_truth(fs,a);ns=numeric_truth(ns,a[0])
                row['success' if ('done',x) in fs and ns==goal else 'wrong']+=1
            g=m.generate_goal((s,v),actions)
            if g is None:goals['abstained']+=1;continue
            goals['generated']+=1;fs,ns=s,v
            for a in g['path']:fs=stage_truth(fs,a);ns=numeric_truth(ns,a[0])
            goals['replayed_success' if (fs,ns)==g['target'] else 'wrong']+=1
    return dict(cases=trials,arms=result,generated_goals=goals)


def falsification_campaign(seeds):
    rows={kind:dict(cases=0,wrong_before_feedback=0,abstained_before_feedback=0,quarantined_after_feedback=0,abstained_after_feedback=0) for kind in ('hidden_symbolic_context','cross_modal_interaction')}
    for seed in seeds:
        m=UnifiedMind();fit,audits,_=symbolic_fixture(seed,'local')
        for o in fit:m.apply('observe',*o)
        for o in audits:m.apply('audit',*o)
        a=('step',f'novel{seed}');s=frozenset({('ready',a[1]),('blocked','external')});t=s
        row=rows['hidden_symbolic_context'];row['cases']+=1;p=m.world.predict(s,a)
        row['wrong_before_feedback']+=p is not None and p!=t;row['abstained_before_feedback']+=p is None
        m.apply('audit',s,a,t);row['quarantined_after_feedback']+=m.world.models[('step',1)].quarantined;row['abstained_after_feedback']+=m.world.predict(s,a) is None
        m=build_joint(seed);a=('prep',f'novel{seed}');s=frozenset({('raw',a[1])});v=(0,0);t=(stage_truth(s,a),(2,0))
        row=rows['cross_modal_interaction'];row['cases']+=1;p=m.predict((s,v),a)
        row['wrong_before_feedback']+=p is not None and p!=t;row['abstained_before_feedback']+=p is None
        m.apply('joint_audit',s,v,a,t[0],t[1]);row['quarantined_after_feedback']+=('prep',1) in m.joint_blocked;row['abstained_after_feedback']+=m.predict((s,v),a) is None
    return rows


def analogy_campaign(seeds):
    row=dict(cases=0,correct_role=0,replayed_goal=0,ambiguous_rejected=0)
    for seed in seeds:
        m=UnifiedMind();prefix=f'a{seed}_'
        def truth(s,a):
            x=a[1];return (s-{('ready',x)})|{('marked',x)} if ('ready',x) in s else s
        for i in range(4):
            x=prefix+'train'+str(i);a=('mark',x)
            for s in (frozenset({('ready',x)}),frozenset()):m.apply('observe',s,a,truth(s,a))
        a,b,c=(prefix+x for x in ('a','b','c'));s=frozenset({('edge',a,b),('edge',b,c),('ready',b)});source=truth(s,('mark',b));m.apply('audit',s,('mark',b),source)
        for i in range(2):
            x=prefix+'audit'+str(i);s=frozenset({('ready',x)});m.apply('audit',s,('mark',x),truth(s,('mark',x)))
        r,u,v=(prefix+x for x in ('r','u','v'));target=frozenset({('edge',r,u),('edge',u,v),('ready',u)});row['cases']+=1
        g=m.analogy_goal(source,target,'edge','marked',b);row['correct_role']+=g==('marked',u)
        p=m.plan(m.joint(target),[('mark',r),('mark',u),('mark',v)],present=[g]);s=target
        if p['path'] is not None:
            for ac in p['path']:s=truth(s,ac)
            row['replayed_goal']+=('marked',u) in s
        try:m.analogy_goal(source,[('edge',r,u),('edge',r,v)],'edge','marked',b)
        except ValueError:row['ambiguous_rejected']+=1
    return row


def recovery_campaign(seeds):
    row=dict(epochs=0,recovered=0,correct=0,incorrect=0,abstained=0,heldout=0,fresh_audit_passes=0)
    for seed in seeds:
        m=UnifiedMind();fit,audits,_=symbolic_fixture(seed,'local')
        for o in fit:m.apply('observe',*o)
        for o in audits:m.apply('audit',*o)
        a=('step',f'shift{seed}');s=[('ready',a[1]),('blocked','external')];m.apply('audit',s,a,s);m.apply('recover',a);row['epochs']+=1
        def sample(name,blocked,noise=False):
            a=('step',name);s=frozenset({('ready',name)}|({('blocked','external')} if blocked else set())|({('noise','other')} if noise else set()));t=s if blocked else symbolic_truth(s,a,'local');return s,a,t
        for i in range(2):m.apply('observe',*sample(f'relearn{seed}_{i}',True))
        for i in range(4):row['fresh_audit_passes']+=m.apply('audit',*sample(f'val{seed}_{i}',bool(i%2)))
        valid=0
        for i in range(8):
            s,a,t=sample(f'held{seed}_{i}',bool(i%2),True);p=m.world.predict(s,a);row['heldout']+=1;row['abstained' if p is None else 'correct' if p==t else 'incorrect']+=1;valid+=p==t
        row['recovered']+=valid==8
    return row


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--trials',type=int,default=12);p.add_argument('--seed',type=int,default=100);a=p.parse_args()
    if not 1<=a.trials<=64:p.error('trials must be 1..64')
    seeds=list(range(a.seed,a.seed+a.trials));print(json.dumps(dict(seeds=seeds,symbolic=symbolic_campaign(seeds),joint=joint_campaign(seeds),analogy=analogy_campaign(seeds),falsification=falsification_campaign(seeds),recovery=recovery_campaign(seeds)),indent=2,default=jsonable))

if __name__=='__main__':main()
